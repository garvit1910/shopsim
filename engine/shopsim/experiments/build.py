"""Spec → run_config expansion (pure; Phase 4, CONTRACT v3.4-draft).

Every builder:
  * emits an ordinary run_config dict that RunConfig.load accepts unchanged;
  * materializes the FULL effective calibration block (all params explicit),
    so config_hash pins every mind constant even when the code defaults move
    later — the calibration-vs-manifest gap closed at the source;
  * records the originating spec under "experiment" (also hash-covered);
  * merges scenario-pack overlays into goals.overrides (base < pack < spec).
"""

from __future__ import annotations

import json
from dataclasses import fields
from pathlib import Path

from ..runner.config import parse_calibration
from .specs import (
    AdExperimentSpec,
    PageABExperimentSpec,
    PricingExperimentSpec,
    ScenarioRunSpec,
    load_pack,
)


def materialize_calibration(block: dict) -> dict:
    """Resolve a (possibly partial) calibration block against the defaults
    and serialize it fully explicit. parse_calibration(materialize(x)) is a
    fixed point — round-trip tested."""
    ap, cp, sb = parse_calibration(block or None)
    return {
        "appraisal": {f.name: getattr(ap, f.name) for f in fields(ap)},
        "choice": {
            **{f.name: getattr(cp, f.name) for f in fields(cp)
               if f.name != "stage_weights"},
            "stage_weights": {stage: dict(dims) for stage, dims in cp.stage_weights},
        },
        "stage_bases": dict(sb),
    }


def _pack_overrides(spec, root: Path) -> dict:
    merged: dict = {}
    for name in spec.scenario_packs:
        pack = load_pack(root, name)
        merged.update(pack.get("goals_overrides", {}))
    return merged


def _population(spec) -> dict:
    """The population block. `social` is emitted ONLY when the spec asks for
    it (CONTRACT v3.9-draft), so every pre-social spec still builds a
    byte-identical config and its config_hash is untouched. The block itself
    is validated downstream by the one authority, runner.config.parse_social,
    when the generated config is loaded."""
    pop = {"size": spec.population_size, "personas": spec.personas}
    if spec.social:
        pop["social"] = dict(spec.social)
    return pop


def _base_raw(spec, root: Path) -> dict:
    return {
        "comment": f"generated by shopsim.experiments ({spec.type})",
        "experiment": {"type": spec.type, "name": spec.name, "spec": spec.raw},
        "label": spec.name,
        "seed": spec.seed,
        "ticks": spec.ticks,
        "t0": spec.t0,
        "tick_seconds": spec.tick_seconds,
        "mind": {"decide": spec.mind_decide, "consolidate": spec.mind_consolidate},
        "population": _population(spec),
        "catalog_dir": spec.catalog,
        "perception_cache": spec.perception_cache,
        "exposure": {
            "frequency_cap_per_tick": spec.frequency_cap_per_tick,
            "frequency_cap_72h": spec.frequency_cap_72h,
            "schedule": [],
        },
        "goals": {"config": spec.goal_config,
                  "overrides": _pack_overrides(spec, root)},
        "fulfillment": {"lag_ticks": spec.fulfillment_lag_ticks,
                        "sat_noise_sd": spec.sat_noise_sd},
        "promos": {"enabled": False},
        "arms": [{"name": "main"}],
        "calibration": materialize_calibration(spec.calibration),
    }


def build_ad_run_config(spec: AdExperimentSpec, root: Path) -> dict:
    """One arm per creative, shared seed: identical populations across arms,
    and identical single-row exposure draws when reach_prob matches — the
    paired comparison the user asked for. Arm c<id>'s results ARE that
    creative's results."""
    raw = _base_raw(spec, root)
    if spec.market.get("shared"):
        # v3.6-draft shared market: ONE arm, every creative row on it. The ads
        # now compete for the same shoppers under the shared frequency caps,
        # and one results.json carries all N creatives (the allocation river's
        # source). allocation{} rides in exposure so config_hash covers it.
        raw["exposure"]["schedule"] = [dict(r) for r in spec.creatives]
        alloc = spec.market.get("allocation")
        if alloc:
            raw["exposure"]["allocation"] = dict(alloc)
        raw["arms"] = [{"name": "market"}]
        return raw
    raw["arms"] = [
        {"name": f"c{row['creative_id']}",
         "exposure_overrides": {"schedule": [row]}}
        for row in spec.creatives
    ]
    return raw


def zeroed_promos(product_promos: list[dict]) -> dict:
    """The promo-OFF arm's schedule: same products, same cycles, every
    discount 0.0. The hook still runs and keeps aligning the shared PRICED_AT
    shelf to list price — an off arm that SKIPPED the hook would read the on
    arm's discounts through the as-of cache (v3.4-draft pricing convention)."""
    return leveled_promos(product_promos, 0.0)


def leveled_promos(product_promos: list[dict], pct: float) -> dict:
    """Same products, same cycles, every discount forced to `pct` — the ladder
    generalization of zeroed_promos (pct 0.0 reproduces it exactly)."""
    return {"product_promos": [
        {"product_id": p["product_id"],
         "cycles": [{**c, "discount_pct": pct} for c in p["cycles"]]}
        for p in product_promos
    ]}


def build_pricing_run_config(spec: PricingExperimentSpec, root: Path) -> dict:
    raw = _base_raw(spec, root)
    raw["exposure"]["schedule"] = [dict(r) for r in spec.exposure]
    if spec.promo_schedule is not None:
        promos_raw = json.loads((root / spec.promo_schedule).read_text())
    else:
        promos_raw = {"product_promos": [dict(p) for p in spec.product_promos]}

    if spec.discount_levels:
        # v3.6-draft ladder: one arm per depth, ASCENDING. Same reasoning as
        # the promo_off/promo_on order — PRICED_AT is shared objective state
        # read as-of t, so the shallowest arm aligns the shelf first and the
        # deepest discount runs last. Every arm runs the promo hook.
        raw["arms"] = [
            {"name": f"d{round(level * 100)}",
             "promo_overrides": {
                 "enabled": True,
                 "schedule_inline": leveled_promos(promos_raw["product_promos"], level)}}
            for level in sorted(spec.discount_levels)
        ]
        return raw
    # BOTH arms inline their schedule: config_hash then covers the promo
    # content itself (a promo-file edit can never silently slip past a
    # resume/branch check — the promo path is not a manifest hash).
    # promo_off FIRST (aligns the shelf to list price), promo_on LAST — the
    # orchestrator runs arms in declared order (v3.4-draft arm ordering).
    raw["arms"] = [
        {"name": "promo_off", "promo_overrides": {
            "enabled": True,
            "schedule_inline": zeroed_promos(promos_raw["product_promos"])}},
        {"name": "promo_on", "promo_overrides": {
            "enabled": True,
            "schedule_inline": {"product_promos": promos_raw["product_promos"]}}},
    ]
    return raw


def build_page_ab_run_config(spec: PageABExperimentSpec, root: Path) -> dict:
    raw = _base_raw(spec, root)
    row: dict = {
        "creative_id": spec.creative_id,
        "start_tick": 0 if spec.start_tick is None else spec.start_tick,
        "end_tick": (spec.ticks - 1) if spec.end_tick is None else spec.end_tick,
        "reach_prob": spec.reach_prob,
        "page_ids": list(spec.page_ids),
    }
    if spec.audience_segments is not None:
        row["audience_segments"] = list(spec.audience_segments)
    raw["exposure"]["schedule"] = [row]
    raw["arms"] = [{"name": "ab"}]
    return raw


def build_scenario_run_config(spec: ScenarioRunSpec, root: Path) -> dict:
    if spec.base_config is not None:
        raw = json.loads((root / spec.base_config).read_text())
        raw["label"] = spec.name
        raw["seed"] = spec.seed
        raw["ticks"] = spec.ticks
        raw["t0"] = spec.t0
        raw["experiment"] = {"type": spec.type, "name": spec.name, "spec": spec.raw}
        raw.setdefault("goals", {}).setdefault("overrides", {})
        raw["calibration"] = materialize_calibration(spec.calibration)
    else:
        raw = _base_raw(spec, root)
        raw["exposure"]["schedule"] = [dict(r) for r in spec.exposure]
        if spec.promo_schedule is not None:
            raw["promos"] = {"schedule": spec.promo_schedule,
                             "enabled": spec.promos_enabled}
    # pack overlays merge under any spec-explicit goal overrides
    overrides = dict(raw["goals"].get("overrides", {}))
    overrides.update(_pack_overrides(spec, root))
    overrides.update(spec.raw.get("goals", {}).get("overrides", {}))
    raw["goals"]["overrides"] = overrides

    if spec.arms:
        raw["arms"] = [dict(a) for a in spec.arms]
    else:
        # default demo lever: the packs' on/off arm pair
        off: dict = {}
        for name in spec.scenario_packs:
            off.update(load_pack(root, name).get("arm_pair", {}).get("off", {}))
        raw["arms"] = [{"name": "wave_on"},
                       {"name": "wave_off",
                        "goal_overrides": off or {"waves_enabled": False}}]
    return raw


def build_run_config(spec, root: Path) -> dict:
    builder = {
        AdExperimentSpec: build_ad_run_config,
        PricingExperimentSpec: build_pricing_run_config,
        PageABExperimentSpec: build_page_ab_run_config,
        ScenarioRunSpec: build_scenario_run_config,
    }[type(spec)]
    return builder(spec, root)
